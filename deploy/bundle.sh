#!/usr/bin/env bash
# Package everything a fresh host needs: the database dump, the filestore
# (attachments: product images, signed PDFs, logos) and the env template.
#
#   ./deploy/bundle.sh
#   scp deploy/bundle/ root@YOUR_SERVER:/root/
#   ssh root@YOUR_SERVER 'cd /root/bundle && ./start.sh'
set -euo pipefail

cd "$(dirname "$0")/.."
OUT=deploy/bundle
DB=vuma_retail

echo "==> collecting database"
mkdir -p "$OUT/restore"
# -Fc custom format: smaller + restorable with pg_restore, and Odoo-safe.
PGPASSWORD="${PGPASSWORD:-}" pg_dump \
    -h "${DB_HOST:-localhost}" -p "${DB_PORT:-5432}" \
    -U "${DB_USER:-odoo}" -d "$DB" \
    --no-owner --no-privileges --format=custom \
    --file "$OUT/restore/vuma_fresh.dump"

echo "==> collecting filestore"
rm -rf "$OUT/filestore"
mkdir -p "$OUT/filestore"
if [ -d "data/filestore/$DB" ]; then
    cp -a "data/filestore/$DB/." "$OUT/filestore/"
else
    echo "WARNING: data/filestore/$DB not found - product images/PDFs will be missing" >&2
fi

echo "==> writing .env"
cat > "$OUT/.env" <<EOF
# Generated by deploy/bundle.sh -- CHANGE THESE before going live.
ADMIN_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=')
DB_PASSWORD=$(openssl rand -base64 24 | tr -d '/+=')
# 0 = threaded server (what the app was tested on); see odoo.conf.template.
WORKERS=0
EOF

echo "==> done"
du -sh "$OUT"
echo
echo "Next:"
echo "  scp -r $OUT root@YOUR_SERVER:/root/"
echo "  ssh root@YOUR_SERVER"
echo "  cd /root/bundle && ./start.sh"
