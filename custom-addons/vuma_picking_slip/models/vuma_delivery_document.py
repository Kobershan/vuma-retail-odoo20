# -*- coding: utf-8 -*-
"""A delivery document for everything loaded onto one truck.

Select the customer invoices that are going on the truck and the document
presents the load in the terms dispatch and the cash office care about:

* how much the goods weigh (product weight x quantity on every invoice);
* how many pallets went on the truck, and how much each weighs (the pallet
  lines dispatch types in on the document -- see ``vuma.delivery.pallet``);
* when the document was generated and by whom;
* how much of the selected invoice value was paid upfront and how much is
  still on account;
* the total selling value of the goods on the truck.

The pallet lines are kept apart from the goods weight so the two
components can always be read side by side: ``total_weight`` stays the
weight of the invoiced products alone. ``total_load_weight`` is the sum
of the two -- the weight actually on the truck -- and is the headline
figure on the printed sheet. Product weights in the catalogue are often
blank, so in practice the load weight is usually just the pallet weight
that dispatch weighed at the scale.

Like the consolidated picking slip, this is a document only. It never
reserves, moves or posts anything.
"""
from collections import OrderedDict
from types import SimpleNamespace

from odoo import _, api, fields, models

from .account_move import _format_quantity


class VumaDeliveryDocument(models.Model):
    _name = 'vuma.delivery.document'
    _description = 'Delivery Document'
    _order = 'generated_at desc, id desc'

    name = fields.Char(
        string='Reference', default=lambda self: _('New'),
        readonly=True, copy=False, required=True)
    generated_at = fields.Datetime(
        string='Generated on', default=fields.Datetime.now,
        readonly=True, copy=False, required=True, index=True)
    generated_by_id = fields.Many2one(
        'res.users', string='Generated by',
        default=lambda self: self.env.user, readonly=True, copy=False,
        required=True)
    company_id = fields.Many2one(
        'res.company', string='Company',
        default=lambda self: self.env.company, required=True, index=True)
    currency_id = fields.Many2one(
        'res.currency', string='Currency', related='company_id.currency_id',
        readonly=True)
    invoice_ids = fields.Many2many(
        'account.move', 'vuma_delivery_document_invoice_rel',
        'document_id', 'invoice_id', string='Invoices on the Truck',
        domain="[('move_type', '=', 'out_invoice'), ('state', '!=', 'cancel')]",
        help='Customer invoices whose goods are loaded on this truck.')
    invoice_count = fields.Integer(
        string='Invoices', compute='_compute_invoice_count')

    total_weight = fields.Float(
        string='Total Weight', compute='_compute_totals', store=True,
        digits='Stock Weight',
        help='Weight of every product on every selected invoice, in the '
             'weight unit configured for products.')
    weight_uom_name = fields.Char(
        string='Weight Unit', compute='_compute_weight_uom_name')
    paid_upfront_amount = fields.Monetary(
        string='Paid Upfront', compute='_compute_totals', store=True,
        currency_field='currency_id',
        help='Invoice value already paid when the document was generated. A '
             'fully paid invoice counts in full; a part-paid invoice counts '
             'only the part that has been paid.')
    on_account_amount = fields.Monetary(
        string='On Account', compute='_compute_totals', store=True,
        currency_field='currency_id',
        help='Invoice value still owing on the selected invoices.')
    total_value = fields.Monetary(
        string='Total Invoice Value', compute='_compute_totals', store=True,
        currency_field='currency_id',
        help='Selling value of the goods on the truck: the total of the '
             'selected customer invoices, including tax.')
    pallet_ids = fields.One2many(
        'vuma.delivery.pallet', 'document_id', string='Pallets',
        help='Pallets loaded on this truck, typed in by dispatch: how many '
             'pallets and how much each one weighs. Kept separate from the '
             'goods weight so palletised goods are never counted twice.')
    total_pallet_quantity = fields.Float(
        string='Pallet Count', compute='_compute_pallet_totals', store=True,
        digits='Product Unit',
        help='Total number of pallets entered on this document. Labelled '
             '"Pallet Count" rather than "Pallets" so it cannot clash with '
             'the label of the pallet_ids line list.')
    total_pallet_weight = fields.Float(
        string='Pallet Weight', compute='_compute_pallet_totals', store=True,
        digits='Stock Weight',
        help='Total weight of the pallets entered on this document, in the '
             'weight unit configured for products.')
    total_load_weight = fields.Float(
        string='Load Weight', compute='_compute_load_weight', store=True,
        digits='Stock Weight',
        help='The weight actually sitting on the truck: the invoiced-goods '
             'weight plus the pallet weight. Product weights in the '
             'catalogue are often blank, so in practice this is usually the '
             'pallet weight -- the figure the scale gives dispatch.')
    note = fields.Text(string='Notes')

    @api.depends('invoice_ids', 'invoice_ids.state')
    def _compute_invoice_count(self):
        for document in self:
            document.invoice_count = len(document._get_delivery_invoices())

    @api.depends(
        'invoice_ids',
        'invoice_ids.state',
        'invoice_ids.amount_total',
        'invoice_ids.amount_residual',
        'invoice_ids.invoice_line_ids.display_type',
        'invoice_ids.invoice_line_ids.quantity',
        'invoice_ids.invoice_line_ids.product_id',
        'invoice_ids.invoice_line_ids.product_uom_id',
        'invoice_ids.invoice_line_ids.product_id.weight',
    )
    def _compute_totals(self):
        for document in self:
            currency = document.currency_id or document.company_id.currency_id \
                or self.env.company.currency_id
            total_weight = 0.0
            total_value = 0.0
            paid_upfront = 0.0
            on_account = 0.0

            for invoice in document._get_delivery_invoices():
                invoice_currency = invoice.currency_id \
                    or invoice.company_id.currency_id
                conversion_date = invoice.invoice_date or invoice.date \
                    or fields.Date.context_today(self)
                total = invoice_currency._convert(
                    invoice.amount_total, currency, document.company_id,
                    conversion_date)
                residual = invoice_currency._convert(
                    invoice.amount_residual, currency, document.company_id,
                    conversion_date)
                total_value += total
                # Negative residuals (overpayments or credit balances) are
                # kept as they are: the cash office needs to see them, not
                # have them silently absorbed into the invoice value.
                paid_upfront += total - residual
                on_account += residual

                for line in invoice.invoice_line_ids:
                    product = line.product_id
                    if line.display_type != 'product' or not product \
                            or product.type == 'service' or line.quantity <= 0:
                        continue
                    line_uom = line.product_uom_id or product.uom_id
                    quantity = line_uom._compute_quantity(
                        line.quantity, product.uom_id)
                    total_weight += quantity * (product.weight or 0.0)

            document.total_weight = total_weight
            document.total_value = total_value
            document.paid_upfront_amount = paid_upfront
            document.on_account_amount = on_account

    @api.depends()
    def _compute_weight_uom_name(self):
        uom_name = self.env['product.template'] \
            ._get_weight_uom_name_from_ir_config_parameter()
        for document in self:
            document.weight_uom_name = uom_name

    @api.depends(
        'pallet_ids',
        'pallet_ids.quantity',
        'pallet_ids.weight_per_pallet',
        'pallet_ids.line_weight',
    )
    def _compute_pallet_totals(self):
        """Sum the manual pallet lines: count and weight of the pallets."""
        for document in self:
            document.total_pallet_quantity = sum(
                document.pallet_ids.mapped('quantity'))
            document.total_pallet_weight = sum(
                document.pallet_ids.mapped('line_weight'))

    @api.depends('total_weight', 'total_pallet_weight')
    def _compute_load_weight(self):
        """The weight on the truck: goods weight plus pallet weight.

        With no pallet lines this equals ``total_weight``. When pallets are
        entered it becomes the figure dispatch actually needs, because the
        catalogue product weights are usually blank.
        """
        for document in self:
            document.total_load_weight = (document.total_weight or 0.0) + \
                (document.total_pallet_weight or 0.0)

    def _get_delivery_invoices(self):
        """The selected records that belong on a delivery document."""
        return self.invoice_ids.filtered(
            lambda invoice: invoice.move_type == 'out_invoice'
            and invoice.state != 'cancel')

    def get_weight_lines(self):
        """Consolidated product quantities and weights for the printed sheet."""
        groups = OrderedDict()
        for invoice in self._get_delivery_invoices():
            for line in invoice.invoice_line_ids:
                product = line.product_id
                if line.display_type != 'product' or not product \
                        or product.type == 'service' or line.quantity <= 0:
                    continue
                line_uom = line.product_uom_id or product.uom_id
                quantity = line_uom._compute_quantity(
                    line.quantity, product.uom_id)
                group = groups.get(product.id)
                if group is None:
                    group = groups[product.id] = {
                        'product': product,
                        'uom': product.uom_id,
                        'quantity': 0.0,
                        'weight': 0.0,
                    }
                group['quantity'] += quantity
                group['weight'] += quantity * (product.weight or 0.0)

        lines = [
            SimpleNamespace(
                product=group['product'],
                uom=group['uom'],
                quantity=group['quantity'],
                quantity_display=_format_quantity(group['quantity']),
                unit_weight=group['product'].weight or 0.0,
                weight=group['weight'],
                weight_display=_format_quantity(group['weight']),
            )
            for group in groups.values()
        ]
        lines.sort(key=lambda line: line.product.display_name or '')
        return lines

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if not vals.get('name') or vals['name'] == _('New'):
                vals['name'] = self.env['ir.sequence'].next_by_code(
                    'vuma.delivery.document') or _('New')
        return super().create(vals_list)

    def action_print_pdf(self):
        """Print the delivery document."""
        self.ensure_one()
        report = self.env.ref(
            'vuma_picking_slip.action_report_delivery_document')
        return report.report_action(self, config=False)

    def action_view_invoices(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Invoices on %(document)s', document=self.name),
            'res_model': 'account.move',
            'view_mode': 'list,form',
            'domain': [('id', 'in', self.invoice_ids.ids)],
        }


class VumaDeliveryPallet(models.Model):
    """One pallet line on a delivery document.

    Dispatch types these in by hand: the truck's real load is counted in
    pallets, and the pallet weight is what the scale says -- product weights
    in the catalogue are often blank, so the invoice-derived weight cannot be
    trusted to tell dispatch how heavy the truck is.

    A line is quantity x weight per pallet. It never touches ``total_weight``
    (the invoiced-goods weight): the two components stay readable side by
    side, and the document adds them once into ``total_load_weight``.
    """
    _name = 'vuma.delivery.pallet'
    _description = 'Delivery Document Pallet'
    _order = 'sequence, id'

    sequence = fields.Integer(default=10)
    document_id = fields.Many2one(
        'vuma.delivery.document', string='Delivery Document',
        required=True, ondelete='cascade', index=True)
    company_id = fields.Many2one(
        related='document_id.company_id', store=True, index=True)
    name = fields.Char(
        string='Pallet', required=True,
        help='What this pallet carries, for example "Cola 2L -- Shoprite" '
             'or "Empty pallets -- return".')
    quantity = fields.Float(
        string='Quantity', required=True, default=1.0,
        digits='Product Unit',
        help='Number of pallets on this line.')
    weight_per_pallet = fields.Float(
        string='Weight per Pallet', digits='Stock Weight',
        help='Weight of one pallet, in the weight unit configured for '
             'products. Leave at zero when the pallets are not weighed.')
    line_weight = fields.Float(
        string='Line Weight', compute='_compute_line_weight', store=True,
        digits='Stock Weight',
        help='Quantity x weight per pallet.')

    @api.depends('quantity', 'weight_per_pallet')
    def _compute_line_weight(self):
        for pallet in self:
            pallet.line_weight = (pallet.quantity or 0.0) * \
                (pallet.weight_per_pallet or 0.0)

    def get_pallet_lines(self):
        """Pallet lines in print order, with quantities pre-formatted."""
        lines = [
            SimpleNamespace(
                name=pallet.name,
                quantity=pallet.quantity,
                quantity_display=_format_quantity(pallet.quantity),
                weight_per_pallet=pallet.weight_per_pallet,
                line_weight=pallet.line_weight,
                line_weight_display=_format_quantity(pallet.line_weight),
            )
            for pallet in self
        ]
        return lines
